import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function discover(kind) {
  const dir = join(root, kind);
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => join(dir, entry.name))
    .filter((pkgDir) => existsSync(join(pkgDir, "package.json")))
    .map((pkgDir) => {
      const pkg = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));
      const exportsField = pkg.exports ?? {};
      return {
        dir: pkgDir,
        name: pkg.name,
        entry: exportsField["."] ?? "./src/index.ts",
        ui: exportsField["./ui"],
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

function importPath(fromDir, pkgDir, file) {
  const path = relative(fromDir, join(pkgDir, file)).replaceAll("\\", "/");
  return path.startsWith(".") ? path : `./${path}`;
}

function writeBackendRegistry(games, connectors) {
  const outDir = join(root, "backend/src/generated");
  mkdirSync(outDir, { recursive: true });
  const lines = ["// Generated by scripts/generate-registry.mjs. Do not edit.", ""];
  games.forEach((game, index) => lines.push(`import game${index} from "${importPath(outDir, game.dir, game.entry)}";`));
  connectors.forEach((connector, index) =>
    lines.push(`import connector${index} from "${importPath(outDir, connector.dir, connector.entry)}";`),
  );
  lines.push("");
  lines.push(`export const gameFactories = [${games.map((_, index) => `game${index}`).join(", ")}];`);
  lines.push(`export const connectorFactories = [${connectors.map((_, index) => `connector${index}`).join(", ")}];`);
  lines.push("");
  writeFileSync(join(outDir, "registry.ts"), lines.join("\n"));
}

function writeFrontendRegistry(games, connectors) {
  const outDir = join(root, "frontend/control/src/generated");
  mkdirSync(outDir, { recursive: true });
  const withUi = [...games, ...connectors].filter((plugin) => plugin.ui);
  const lines = ["// Generated by scripts/generate-registry.mjs. Do not edit.", ""];
  withUi.forEach((plugin, index) => lines.push(`import ui${index} from "${importPath(outDir, plugin.dir, plugin.ui)}";`));
  lines.push("");
  lines.push("export const pluginUi: Record<string, unknown> = {");
  withUi.forEach((plugin, index) => lines.push(`  ${JSON.stringify(plugin.name)}: ui${index},`));
  lines.push("};");
  lines.push("");
  writeFileSync(join(outDir, "registry.ts"), lines.join("\n"));
}

const games = discover("games");
const connectors = discover("connectors");
writeBackendRegistry(games, connectors);
writeFrontendRegistry(games, connectors);
console.log(`registry: ${games.length} game(s), ${connectors.length} connector(s)`);
